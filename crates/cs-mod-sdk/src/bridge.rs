/// Packs `[r, g, b, a]` into the big-endian `i32` wire format expected by `cs16_mod` host calls.
#[inline]
pub const fn pack_rgba(rgba: [u8; 4]) -> i32 {
    (((rgba[0] as u32) << 24)
        | ((rgba[1] as u32) << 16)
        | ((rgba[2] as u32) << 8)
        | (rgba[3] as u32)) as i32
}

/// Packs `[r, g, b]` into the 24-bit `i32` wire format expected by `cs16_mod` host calls.
#[inline]
pub const fn pack_rgb(rgb: [u8; 3]) -> i32 {
    (((rgb[0] as u32) << 16) | ((rgb[1] as u32) << 8) | (rgb[2] as u32)) as i32
}

/// Serializes a [`CustomWeaponSpec`] into the newline-delimited `key=value` text accepted by
/// `cs16_mod::register_custom_weapon`.
pub fn encode_custom_weapon_spec(spec: &CustomWeaponSpec) -> String {
    let mut out = format!(
        "id={}\nbase_weapon={}\ndisplay_name={}\ndamage_mult={}\ndeploy_speed_mult={}\nrecoil_mult={}\nknockback={}\ncost={}\n",
        spec.id_name,
        spec.base_weapon,
        spec.display_name,
        spec.damage_mult,
        spec.deploy_speed_mult,
        spec.recoil_mult,
        spec.knockback,
        spec.cost,
    );
    if let Some(ref m) = spec.v_model {
        out.push_str(&format!("v_model={m}\n"));
    }
    if let Some(ref m) = spec.p_model {
        out.push_str(&format!("p_model={m}\n"));
    }
    if let Some(ref m) = spec.w_model {
        out.push_str(&format!("w_model={m}\n"));
    }
    if let Some(ref s) = spec.fire_sound {
        out.push_str(&format!("fire_sound={s}\n"));
    }
    if let Some(clip) = spec.clip_size {
        out.push_str(&format!("clip_size={clip}\n"));
    }
    out
}

/// Encodes named/positional `lang_tr` parameters into newline-delimited `key=val` wire format.
pub fn encode_lang_args(args: &[(&str, &str)]) -> String {
    let mut out = String::new();
    for (idx, (k, v)) in args.iter().enumerate() {
        if idx > 0 {
            out.push('\n');
        }
        let clean_v = v.replace(['\r', '\n'], " ");
        if k.is_empty() {
            out.push_str(&clean_v);
        } else {
            out.push_str(k);
            out.push('=');
            out.push_str(&clean_v);
        }
    }
    out
}

/// Parses the tab-delimited `"{rank}\t{total}\t{score}\t{payload}"` line returned by
/// `cs16_mod::leaderboard_rank`.
pub fn parse_leaderboard_rank_row(
    key: &str,
    raw: &str,
) -> Option<(LeaderboardEntry, usize)> {
    let mut parts = raw.splitn(4, '\t');
    let rank = parts.next()?.parse::<usize>().ok()?;
    let total = parts.next()?.parse::<usize>().ok()?;
    let score = parts.next()?.parse::<f64>().ok()?;
    let payload_json = parts.next().unwrap_or("").to_string();
    Some((
        LeaderboardEntry {
            rank,
            key: key.to_string(),
            score,
            payload_json,
        },
        total,
    ))
}

/// Parses the newline-delimited `"{rank}\t{key}\t{score}\t{payload}\n"` rows returned by
/// `cs16_mod::leaderboard_top`.
pub fn parse_leaderboard_top_rows(raw: &str) -> Vec<LeaderboardEntry> {
    let mut out = Vec::new();
    for line in raw.lines() {
        if line.is_empty() {
            continue;
        }
        let mut parts = line.splitn(4, '\t');
        let (Some(rank_s), Some(key), Some(score_s)) =
            (parts.next(), parts.next(), parts.next())
        else {
            continue;
        };
        let (Ok(rank), Ok(score)) = (rank_s.parse::<usize>(), score_s.parse::<f64>()) else {
            continue;
        };
        let payload_json = parts.next().unwrap_or("").to_string();
        out.push(LeaderboardEntry {
            rank,
            key: key.to_string(),
            score,
            payload_json,
        });
    }
    out
}

