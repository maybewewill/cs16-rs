#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum WeaponSlot {
    Primary = 1,
    Secondary = 2,
    Melee = 3,
    Grenade = 4,
    C4 = 5,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum TeamRestriction {
    Any,
    Terrorist,
    CounterTerrorist,
}

/// Exact ReGameDLL_CS `CBasePlayerWeapon::KickBack` parameters.
#[derive(Debug, Clone, Copy)]
pub struct KickBackParams {
    pub up_base: f32,
    pub lateral_base: f32,
    pub up_modifier: f32,
    pub lateral_modifier: f32,
    pub up_max: f32,
    pub lateral_max: f32,
    pub direction_change: i32,
}

impl KickBackParams {
    pub const ZERO: Self = Self {
        up_base: 0.0,
        lateral_base: 0.0,
        up_modifier: 0.0,
        lateral_modifier: 0.0,
        up_max: 0.0,
        lateral_max: 0.0,
        direction_change: 0,
    };
}

