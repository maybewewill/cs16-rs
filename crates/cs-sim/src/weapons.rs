/// Exact ReGameDLL_CS `CBasePlayerWeapon::KickBack` pitch/yaw recoil state step!
/// Updates `(punch_pitch, punch_yaw, recoil_dir)` in-place using CS 1.6 movement/stance multipliers.
#[allow(clippy::too_many_arguments)]
pub fn apply_regamedll_kickback(
    kick: KickBackParams,
    shots_fired: u32,
    horiz_speed: f32,
    on_ground: bool,
    crouched: bool,
    punch_pitch: &mut f32,
    punch_yaw: &mut f32,
    recoil_dir: &mut i8,
    rand_u32: u32,
) {
    // Stance multipliers matching ReGameDLL_CS per-weapon branching (air > moving > standing > crouched)
    let stance = if !on_ground {
        1.45
    } else if horiz_speed > 140.0 {
        1.20
    } else if crouched {
        0.78
    } else {
        1.0
    };

    let (kick_up, kick_lat) = if shots_fired <= 1 {
        (kick.up_base * stance, kick.lateral_base * stance)
    } else {
        (
            (kick.up_base + (shots_fired as f32) * kick.up_modifier) * stance,
            (kick.lateral_base + (shots_fired as f32) * kick.lateral_modifier) * stance,
        )
    };

    // Pitch kicks upward (negative pitch in GoldSrc) clamped at `-up_max * stance`
    let max_up = kick.up_max * stance;
    *punch_pitch -= kick_up;
    if *punch_pitch < -max_up {
        *punch_pitch = -max_up;
    }

    // Horizontal recoil walks in `recoil_dir` and flips cleanly at `lateral_max` or `1 / direction_change`
    let max_lat = kick.lateral_max * stance;
    if *recoil_dir == 0 {
        *recoil_dir = 1;
    }
    if *recoil_dir > 0 {
        *punch_yaw += kick_lat;
        if *punch_yaw > max_lat {
            *punch_yaw = max_lat;
            *recoil_dir = -1;
        }
    } else {
        *punch_yaw -= kick_lat;
        if *punch_yaw < -max_lat {
            *punch_yaw = -max_lat;
            *recoil_dir = 1;
        }
    }

    if kick.direction_change > 0 && (rand_u32 as i32 % kick.direction_change) == 0 {
        *recoil_dir = -*recoil_dir;
    }
}

/// Exact Half-Life / GoldSrc `PM_DropPunchAngle` smooth spring decay (`len -= (10 + len * 0.5) * dt`).
pub fn pm_drop_punch_angle(punch_pitch: &mut f32, punch_yaw: &mut f32, dt: f32) {
    let len = (*punch_pitch * *punch_pitch + *punch_yaw * *punch_yaw).sqrt();
    if len <= 1e-4 {
        *punch_pitch = 0.0;
        *punch_yaw = 0.0;
        return;
    }
    let next_len = (len - (10.0 + len * 0.5) * dt).max(0.0);
    let scale = next_len / len;
    *punch_pitch *= scale;
    *punch_yaw *= scale;
}

/// Compute authentic CS 1.6 final health & armor damage using ReGameDLL_CS armor ratio math.
/// Returns `(hp_damage, armor_damage)`.
pub fn compute_cs16_damage(
    base_damage: f32,
    distance: f32,
    range_modifier: f32,
    hitgroup: HitGroup,
    armor_ratio: f32,
    victim_armor: f32,
    victim_helmet: bool,
) -> (f32, f32) {
    let dist_falloff = range_modifier.powf(distance / 500.0);
    let mut dmg = base_damage * dist_falloff * hitgroup.damage_multiplier();

    if victim_armor > 0.0 && hitgroup.is_armored(victim_helmet) {
        let ratio = armor_ratio * 0.5;
        let bonus = 0.5f32;
        let new_dmg = dmg * ratio;
        let mut armor_dmg = (dmg - new_dmg) * bonus;
        if armor_dmg > victim_armor {
            armor_dmg = victim_armor;
            dmg -= armor_dmg / bonus;
        } else {
            dmg = new_dmg;
        }
        return (dmg.max(1.0), armor_dmg.max(0.0));
    }

    (dmg.max(1.0), 0.0)
}

/// Compute effective angular spread (radians) for a shot given movement, air state, crouching, zoom, and spray count.
pub fn compute_shot_spread(
    spec: &WeaponSpec,
    horiz_speed: f32,
    on_ground: bool,
    crouched: bool,
    zoom_level: u8,
    shots_fired: u32,
) -> f32 {
    let mut spread = spec.base_spread;
    if spec.has_scope && spec.double_zoom && zoom_level == 0 {
        spread += 0.075;
    }
    if !on_ground {
        spread += spec.air_spread;
    } else if horiz_speed > 25.0 {
        let move_factor = (horiz_speed / spec.max_speed.max(1.0)).clamp(0.0, 1.2);
        spread += spec.move_spread * move_factor;
    }
    if crouched && on_ground {
        spread *= 0.72;
    }
    if shots_fired > 0 {
        let spray = (shots_fired as f32).min(12.0) * 0.0052;
        spread += spray;
    }
    spread
}
