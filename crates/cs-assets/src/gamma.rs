//! GoldSrc gamma LUTs (`BuildGammaTable`), texture gamma conversion, `R_BuildLightMap`,
//! and lightstyle scaling.
//!
//! Ported from Xash3D FWGS (`engine/client/gamma.c` `BuildGammaTable`, `V_ValidateGammaCvars`,
//! `TextureToGamma`, `LightToTexGamma`, `ScreenGammaTable`, `LinearGammaTable`;
//! `ref/gl/gl_rsurf.c` `R_BuildLightMap`; `ref/common/ref_light.c` `CL_RunLightStyles`),
//! all read 2026-11-24.

/// Validated GoldSrc gamma settings matching Xash3D FWGS `V_ValidateGammaCvars` defaults & bounds.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct GoldSrcGammaConfig {
    pub gamma: f32,
    pub brightness: f32,
    pub texgamma: f32,
    pub lightgamma: f32,
}

impl Default for GoldSrcGammaConfig {
    fn default() -> Self {
        Self {
            gamma: 2.5,
            brightness: 0.0,
            texgamma: 2.0,
            lightgamma: 2.5,
        }
    }
}

impl GoldSrcGammaConfig {
    /// Clamp CVars according to `V_ValidateGammaCvars` (`engine/client/gamma.c:82-103`, read 2026-11-24).
    pub fn validated(self) -> Self {
        Self {
            gamma: if self.gamma.is_finite() {
                self.gamma.clamp(1.8, 3.0)
            } else {
                2.5
            },
            brightness: if self.brightness.is_finite() {
                self.brightness.clamp(0.0, 3.0)
            } else {
                0.0
            },
            texgamma: if self.texgamma.is_finite() {
                self.texgamma.clamp(1.8, 3.0)
            } else {
                2.0
            },
            lightgamma: if self.lightgamma.is_finite() {
                self.lightgamma.clamp(1.8, 3.0)
            } else {
                2.5
            },
        }
    }
}

/// Exact GoldSrc lookup tables generated by `BuildGammaTable` (`engine/client/gamma.c:35-80`,
/// read 2026-11-24).
#[derive(Debug, Clone, PartialEq)]
pub struct GammaTables {
    pub config: GoldSrcGammaConfig,
    pub texgammatable: [u8; 256],
    pub lightgammatable: [u16; 1024],
    pub lineargammatable: [u16; 1024],
    pub screengammatable: [u16; 1024],
}

impl Default for GammaTables {
    fn default() -> Self {
        Self::build(GoldSrcGammaConfig::default())
    }
}

impl GammaTables {
    /// Port of `BuildGammaTable` (`engine/client/gamma.c:35-80`, read 2026-11-24).
    ///
    /// Keeps the exact C `float`/`double` casts so every entry of all four LUTs matches
    /// Xash3D's `Test_PrecomputedGammaTables` bit-for-bit.
    pub fn build(raw: GoldSrcGammaConfig) -> Self {
        let cfg = raw.validated();
        let gamma = cfg.gamma;
        let brightness = cfg.brightness;
        let texgamma = cfg.texgamma;
        let lightgamma = cfg.lightgamma;

        let g1: f32 = if gamma != 0.0 {
            (1.0_f64 / f64::from(gamma)) as f32
        } else {
            0.4
        };
        let g2: f32 = g1 * texgamma;
        let g3: f32 = if brightness <= 0.0 {
            0.125
        } else if brightness <= 1.0 {
            (0.125_f64 - f64::from(brightness) * f64::from(brightness) * 0.075_f64) as f32
        } else {
            0.05
        };

        let mut texgammatable = [0u8; 256];
        for (i, slot) in texgammatable.iter_mut().enumerate() {
            // Quirk: `BuildGammaTable` computes `(float)pow( i / 255.0, (double)g2 )` then `* 255.0f`
            // truncated to `int` (`gamma.c:55-57`).
            let d: f32 = (f64::from(i as u32) / 255.0).powf(f64::from(g2)) as f32;
            let inf: i32 = (d * 255.0f32) as i32;
            *slot = inf.clamp(0, 255) as u8;
        }

        let mut lightgammatable = [0u16; 1024];
        let mut lineargammatable = [0u16; 1024];
        let mut screengammatable = [0u16; 1024];
        for i in 0..1024usize {
            let mut f: f32 = (f64::from(i as u32) / 1023.0).powf(f64::from(lightgamma)) as f32;
            if brightness > 1.0 {
                f *= brightness;
            }
            if f <= g3 {
                f = ((f64::from(f) / f64::from(g3)) * 0.125_f64) as f32;
            } else {
                f = (((f64::from(f) - f64::from(g3)) / (1.0_f64 - f64::from(g3))) * 0.875_f64
                    + 0.125_f64) as f32;
            }
            // Quirk: keep `(double)f` for `pow`, otherwise entries drift by 1 (`gamma.c:72`).
            let d: f64 = f64::from(f).powf(f64::from(g1));
            let inf: i32 = (d * 1023.0) as i32;
            lightgammatable[i] = inf.clamp(0, 1023) as u16;

            lineargammatable[i] =
                ((f64::from(i as u32) / 1023.0).powf(f64::from(gamma)) * 1023.0) as u16;
            screengammatable[i] =
                ((f64::from(i as u32) / 1023.0).powf(1.0 / f64::from(gamma)) * 1023.0) as u16;
        }

        Self {
            config: cfg,
            texgammatable,
            lightgammatable,
            lineargammatable,
            screengammatable,
        }
    }

    /// `TextureToGamma(b)` (`engine/client/gamma.c:175-181`, read 2026-11-24).
    #[inline]
    pub fn texture_to_gamma(&self, b: u8) -> u8 {
        self.texgammatable[usize::from(b)]
    }

    /// 8-bit `LightToTexGamma(b)` (`engine/client/gamma.c:183-190`, read 2026-11-24).
    #[inline]
    pub fn light_to_tex_gamma_u8(&self, b: u8) -> u8 {
        (self.lightgammatable[usize::from(b) << 2] >> 2) as u8
    }

    /// 10-bit `LightToTexGamma(b)` returning `[0.0, 1.0]` as used in `R_StudioLighting`
    /// (`ref/gl/gl_local.h:727`, `ref/gl/gl_studio.c:1369`, read 2026-11-24).
    #[inline]
    pub fn light_to_tex_gamma_unit(&self, b_10bit: u32) -> f32 {
        let idx = b_10bit.min(1023) as usize;
        f32::from(self.lightgammatable[idx]) / 1023.0
    }

    /// Apply `texgammatable` in place to the RGB channels of an RGBA8 buffer (alpha untouched),
    /// matching `LUMP_TEXGAMMA` (`engine/common/imagelib/img_utils.c:292-301`, read 2026-11-24).
    pub fn apply_texgamma_rgba(&self, rgba: &mut [u8]) {
        for px in rgba.as_chunks_mut::<4>().0 {
            px[0] = self.texgammatable[usize::from(px[0])];
            px[1] = self.texgammatable[usize::from(px[1])];
            px[2] = self.texgammatable[usize::from(px[2])];
        }
    }

    /// Compute `lightscale` for `R_BuildLightMap` (`ref/gl/gl_rsurf.c:741-744`, read 2026-11-24).
    ///
    /// At `lightgamma = 2.5` and `gl_overbright = false`, this evaluates to `338`.
    #[inline]
    pub fn lightscale(&self, gl_overbright: bool) -> u32 {
        if gl_overbright {
            256
        } else {
            (2.0_f64.powf(1.0 / f64::from(self.config.lightgamma)) * 256.0 + 0.5) as u32
        }
    }
}

/// Convert normalized `cs-clientcore` style multiplier (`1.0` for `'m'`) to GoldSrc
/// `g_lightstylevalue[i]` (`ref/common/ref_light.c:52-86`, read 2026-11-24: `(b - 'a') * 22`).
#[inline]
pub fn lightstyle_f32_to_scale(mul: f32) -> u32 {
    if !mul.is_finite() || mul <= 0.0 {
        0
    } else {
        (mul * 264.0).round().clamp(0.0, 65536.0) as u32
    }
}

/// Convert a lightmap pattern character (`'a'`..=`'z'`) to `g_lightstylevalue`
/// (`ref/common/ref_light.c:60`, read 2026-11-24).
#[inline]
pub fn lightstyle_char_to_scale(ch: u8) -> u32 {
    u32::from(ch.saturating_sub(b'a')) * 22
}

/// Port of `R_BuildLightMap` inner luxel transform (`ref/gl/gl_rsurf.c:792-821`, read 2026-11-24).
///
/// Combines pre-summed `blocklights[c]` (`sum(lm[c] * g_lightstylevalue) + dlight`),
/// scales by `lightscale >> 14`, clamps to `1023`, and maps via `lightgammatable[t] >> 2`.
#[inline]
pub fn build_lightmap_pixel(bl: [u32; 3], lightscale: u32, tables: &GammaTables) -> [u8; 4] {
    let mut out = [0u8, 0u8, 0u8, 255u8];
    for c in 0..3 {
        let t = ((bl[c].saturating_mul(lightscale)) >> 14).min(1023) as usize;
        out[c] = (tables.lightgammatable[t] >> 2) as u8;
    }
    out
}

